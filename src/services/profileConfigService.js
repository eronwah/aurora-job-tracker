const PRIVATE_CONFIG_KEY = "aurora_job_tracker_private_config";
const LEGACY_GAS_KEY = "aurora_job_tracker_gas_url";

const DEFAULT_PRIVATE_CONFIG = {
  email: "",
  phone: "",
  location: "Philippines (Remote)",
  linkedin: "",
  driveResumeUrl: "",
  sheetUrl: "",
  gasWebhookUrl: ""
};

/**
 * Loads user-specific private contact details, Google Drive resume link,
 * Google Sheet URL, and Apps Script webhook URL exclusively from browser localStorage.
 * Keeps public GitHub repositories free of personal contact details or private file IDs.
 */
export function getPrivateConfig() {
  try {
    const raw = localStorage.getItem(PRIVATE_CONFIG_KEY);
    const legacyGasUrl = localStorage.getItem(LEGACY_GAS_KEY) || "";

    if (!raw) {
      return {
        ...DEFAULT_PRIVATE_CONFIG,
        gasWebhookUrl: legacyGasUrl
      };
    }

    const parsed = JSON.parse(raw);
    return {
      ...DEFAULT_PRIVATE_CONFIG,
      ...parsed,
      location: parsed.location || DEFAULT_PRIVATE_CONFIG.location,
      gasWebhookUrl: parsed.gasWebhookUrl || legacyGasUrl
    };
  } catch (err) {
    console.error("Failed to read private config:", err);
    return { ...DEFAULT_PRIVATE_CONFIG };
  }
}

/**
 * Merges and saves private configuration into browser localStorage.
 */
export function savePrivateConfig(partial = {}) {
  try {
    const current = getPrivateConfig();
    const trimmed = Object.fromEntries(
      Object.entries(partial).map(([k, v]) => [k, typeof v === "string" ? v.trim() : v])
    );
    const next = {
      ...current,
      ...trimmed,
      location: trimmed.location !== undefined ? (trimmed.location || "Philippines (Remote)") : current.location
    };
    localStorage.setItem(PRIVATE_CONFIG_KEY, JSON.stringify(next));
    if (trimmed.gasWebhookUrl !== undefined) {
      localStorage.setItem(LEGACY_GAS_KEY, next.gasWebhookUrl || "");
    }
    return next;
  } catch (err) {
    console.error("Failed to save private config:", err);
    return getPrivateConfig();
  }
}

/**
 * Extracts a Google Drive File ID from a Drive URL or returns the raw ID if already an ID.
 */
export function extractDriveFileId(urlOrId = "") {
  if (!urlOrId || typeof urlOrId !== "string") return "";
  const trimmed = urlOrId.trim();
  if (!trimmed) return "";

  const matchPath = trimmed.match(/\/d\/([a-zA-Z0-9_-]+)/);
  if (matchPath && matchPath[1]) return matchPath[1];

  const matchQuery = trimmed.match(/[?&]id=([a-zA-Z0-9_-]+)/);
  if (matchQuery && matchQuery[1]) return matchQuery[1];

  if (/^[a-zA-Z0-9_-]{15,}$/.test(trimmed)) return trimmed;
  return "";
}

/**
 * Encodes the current private config as a compact UTF-8-safe base64 setup code
 * for quick Desktop -> iPhone transfer.
 */
export function exportSetupCode() {
  const config = getPrivateConfig();
  const jsonStr = JSON.stringify(config);
  const bytes = new TextEncoder().encode(jsonStr);
  let binary = "";
  bytes.forEach((b) => {
    binary += String.fromCharCode(b);
  });
  return `AURORA-CFG:${btoa(binary)}`;
}

/**
 * Decodes and imports a setup code generated by exportSetupCode().
 */
export function importSetupCode(code = "") {
  try {
    const trimmed = code.trim();
    if (!trimmed) {
      return { success: false, message: "Paste your setup transfer code first." };
    }
    const payload = trimmed.startsWith("AURORA-CFG:")
      ? trimmed.slice("AURORA-CFG:".length)
      : trimmed;

    const binary = atob(payload);
    const bytes = Uint8Array.from(binary, (c) => c.charCodeAt(0));
    const jsonStr = new TextDecoder().decode(bytes);
    const parsed = JSON.parse(jsonStr);

    if (!parsed || typeof parsed !== "object") {
      return { success: false, message: "Invalid setup code format." };
    }

    const saved = savePrivateConfig({
      email: parsed.email || "",
      phone: parsed.phone || "",
      location: parsed.location || "Philippines (Remote)",
      linkedin: parsed.linkedin || "",
      driveResumeUrl: parsed.driveResumeUrl || "",
      sheetUrl: parsed.sheetUrl || "",
      gasWebhookUrl: parsed.gasWebhookUrl || ""
    });

    return {
      success: true,
      config: saved,
      message: "Setup imported! Contact info, Drive link, and Google Sheet sync are now active on this device."
    };
  } catch (err) {
    return {
      success: false,
      message: "Could not read that setup code. Make sure you copied the full string."
    };
  }
}
